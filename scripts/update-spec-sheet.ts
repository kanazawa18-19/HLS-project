async function main() {
  const values = rows.map((r) => [r]);
  await overwriteSheet(SPREADSHEET_ID, SHEET_NAME, values);
  await setColumnWidth(SPREADSHEET_ID, SHEET_NAME, 0, 900);
  await wrapColumn(SPREADSHEET_ID, SHEET_NAME, 0);

  const sectionHeaderIdx = rows
    .map((r, i) => ({ r, i }))
    .filter(({ r }) => r !== null && /^\d+\.\s/.test(r))
    .map(({ i }) => i);
  await boldRows(SPREADSHEET_ID, SHEET_NAME, [0], 14);
  await boldRows(SPREADSHEET_ID, SHEET_NAME, sectionHeaderIdx, 12);

  console.log(`完了: 「${SHEET_NAME}」シートを更新しました(${rows.length}行、見出し${sectionHeaderIdx.length}箇所を太字化)`);
  console.log(`https://docs.google.com/spreadsheets/d/${SPREADSHEET_ID}/edit`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
